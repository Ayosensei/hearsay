import ts from "typescript";
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const sourceDirectory = join(root, "packages", "hearsay", "src", "queries");
const output = join(root, "queries");
const check = process.argv.includes("--check");
const entries = new Map();
function literal(node) {
  if (
    !node ||
    !(ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node))
  )
    throw new Error("Query mirrors require fixed literal query text.");
  return node.text.replace(/\r\n/g, "\n");
}
function add(id, query, source) {
  if (entries.has(id)) throw new Error(`Duplicate canonical query: ${id}`);
  entries.set(id, {
    id,
    query,
    source,
    sha256: createHash("sha256").update(query).digest("hex"),
  });
}
for (const name of (await readdir(sourceDirectory))
  .filter((n) => n.endsWith(".ts"))
  .sort()) {
  const text = await readFile(join(sourceDirectory, name), "utf8");
  const file = ts.createSourceFile(name, text, ts.ScriptTarget.Latest, true);
  for (const statement of file.statements) {
    if (
      !ts.isVariableStatement(statement) ||
      !statement.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword)
    )
      continue;
    for (const declaration of statement.declarationList.declarations) {
      const id = declaration.name.getText(file);
      if (/^Q\d/.test(id))
        add(
          id,
          literal(declaration.initializer),
          `packages/hearsay/src/queries/${name}`,
        );
      if (id === "INDEX_QUERIES") {
        let value = declaration.initializer;
        while (
          value &&
          (ts.isAsExpression(value) || ts.isParenthesizedExpression(value))
        )
          value = value.expression;
        if (!value || !ts.isArrayLiteralExpression(value))
          throw new Error("Expected literal index catalogue.");
        for (const pair of value.elements) {
          if (!ts.isArrayLiteralExpression(pair))
            throw new Error("Expected literal index pair.");
          add(
            literal(pair.elements[0]),
            literal(pair.elements[1]),
            `packages/hearsay/src/queries/${name}`,
          );
        }
      }
    }
  }
}
const sorted = [...entries.values()].sort((a, b) =>
  a.id < b.id ? -1 : a.id > b.id ? 1 : 0,
);
const expected = new Map(
  sorted.map((entry) => [
    `${entry.id}.cypher`,
    `// Generated by scripts/query-mirror.mjs; do not edit.\n// ${entry.id} — canonical source: ${entry.source}\n${entry.query}\n`,
  ]),
);
expected.set(
  "manifest.json",
  JSON.stringify(
    sorted.map(({ id, source, sha256 }) => ({ id, source, sha256 })),
    null,
    2,
  ) + "\n",
);
let failures = 0;
if (!check) await mkdir(output, { recursive: true });
for (const [name, content] of expected) {
  if (check) {
    let actual = "";
    try {
      actual = (await readFile(join(output, name), "utf8")).replace(
        /\r\n/g,
        "\n",
      );
    } catch {}
    if (actual !== content) {
      console.error(`Query mirror differs: ${name}`);
      failures++;
    }
  } else await writeFile(join(output, name), content);
}
for (const name of await readdir(output))
  if (name.endsWith(".cypher") && !expected.has(name)) {
    console.error(`Stale or extra mirror: ${name}`);
    failures++;
  }
if (failures) process.exitCode = 1;
else
  console.log(
    `${check ? "Verified" : "Generated"} ${sorted.length} canonical Cypher mirrors and manifest.`,
  );
